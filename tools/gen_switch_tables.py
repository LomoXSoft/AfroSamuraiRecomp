#!/usr/bin/env python3
"""Generate [[switch_tables]] overrides for jump tables the codegen truncates
(it stops at 512 entries). Reads the decrypted PE (VA = 0x82000000 + offset)
and scans every bctr preceded by cmplwi + lis/addi table. Emits entries only
for tables with > 512 entries. Output is game-derived: keep it private
(gitignored). usage: gen_switch_tables.py default.pe out.toml"""
import struct, sys
d = open(sys.argv[1], 'rb').read()
B = 0x82000000
W = lambda a: struct.unpack('>I', d[a - B:a - B + 4])[0]
out = ['# Generated by tools/gen_switch_tables.py - game-derived, do not commit']
for off in range(0, len(d) - 4, 4):
    if struct.unpack('>I', d[off:off + 4])[0] != 0x4E800420:
        continue
    a = B + off
    lis = addi = cmp = None
    for k in range(1, 12):
        w = W(a - 4 * k); op = w >> 26
        if op == 15 and lis is None: lis = (w & 0xffff) << 16
        if op == 14 and addi is None: addi = w & 0xffff
        if op == 10 and cmp is None: cmp = (w & 0xffff, (w >> 16) & 31)
    if None in (lis, addi, cmp) or cmp[0] + 1 <= 512:
        continue
    tab = (lis + ((addi ^ 0x8000) - 0x8000)) & 0xffffffff
    n = cmp[0] + 1
    o = tab - B
    if o < 0 or o + 4 * n > len(d):
        continue
    t = struct.unpack('>%dI' % n, d[o:o + 4 * n])
    if not all(B <= x < B + len(d) for x in t):
        continue
    out.append('\n[[switch_tables]]\naddress = 0x%08X\nregister = %d\nlabels = [%s]'
               % (a, cmp[1], ','.join('0x%08X' % x for x in t)))
    print('bctr 0x%08X table 0x%08X entries %d' % (a, tab, n))
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
