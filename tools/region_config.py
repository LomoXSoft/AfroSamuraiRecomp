#!/usr/bin/env python3
"""Pick the disc region from app/assets/default.xex and write the codegen inputs for it.

usage: region_config.py <app dir>

Writes app/region/ (ignored by Git):
  afro_hooks.toml, afro_functions.toml  the Europe files, with every address
                                         moved to the USA build when needed
  afro_region.h                          AfroGameAddr(), the same map for the C++
  region.txt                             eu or usa
Files are only rewritten when their text changes, so an unchanged region does
not make the build run codegen again. When the region changes, the files made
from the previous executable (PE, switch tables, icon, codegen stamp) are
removed so the build makes them again for the new one.
"""
from __future__ import annotations

import hashlib
import pathlib
import re
import sys
import tomllib

XEX_SHA1 = {
    "5e831c64173b4a24805bc9c0c0eb860b3d7f53c6": "eu",
    "873fff7191be2b687eb55f8564f9b9f5c5842b40": "usa",
}
NAMES = {"eu": "Europe", "usa": "USA"}
ADDR = re.compile(r"0x8[23][0-9A-Fa-f]{6}")
# Calls in the C++ sources that must have an entry in the map.
CALL = re.compile(r"AfroGameAddr\(\s*(0x[0-9A-Fa-f]{8})\s*\)")


def load_map(app: pathlib.Path, region: str) -> dict[int, int] | None:
    if region == "eu":
        return None
    data = tomllib.loads((app / "regions" / f"{region}.toml").read_text(encoding="utf-8"))
    out: dict[int, int] = {}
    for table in ("code", "data"):
        for k, v in data.get(table, {}).items():
            out[int(k, 16)] = int(v)
    return out


def move_toml(text: str, amap: dict[int, int] | None, name: str) -> str:
    if amap is None:
        return text
    lines = []
    for n, line in enumerate(text.splitlines(keepends=True), 1):
        code, hash_, comment = line.partition("#")

        def sub(m: re.Match[str]) -> str:
            eu = int(m.group(0), 16)
            if eu not in amap or amap[eu] == 0:
                raise SystemExit(f"region_config: {name}:{n}: 0x{eu:08X} has no USA address in app/regions/usa.toml")
            return f"0x{amap[eu]:08X}"

        lines.append(ADDR.sub(sub, code) + hash_ + comment)
    return "".join(lines)


def header(region: str, amap: dict[int, int] | None) -> str:
    out = [
        "// Generated by tools/region_config.py from app/regions. Do not edit.",
        "#pragma once",
        "#include <cstdint>",
        f'#define AFRO_REGION_NAME "{NAMES[region]}"',
        f"#define AFRO_REGION_USA {1 if region == 'usa' else 0}",
        "// Europe address -> this disc's address. 0 = not present on this disc.",
        "constexpr uint32_t AfroGameAddr(uint32_t eu) {",
    ]
    if amap:
        out.append("  switch (eu) {")
        out += [f"    case 0x{k:08X}u: return 0x{v:08X}u;" for k, v in sorted(amap.items())]
        out.append("    default: return eu;")
        out.append("  }")
    else:
        out.append("  return eu;")
    out.append("}")
    return "\n".join(out) + "\n"


def write_if_changed(path: pathlib.Path, text: str) -> bool:
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8", newline="\n")
    return True


def main() -> int:
    app = pathlib.Path(sys.argv[1]).resolve()
    xex = app / "assets" / "default.xex"
    sha1 = hashlib.sha1(xex.read_bytes()).hexdigest()
    region = XEX_SHA1.get(sha1)
    if region is None:
        print(f"region_config: default.xex SHA-1 {sha1} is not a supported disc "
              "(Europe or USA retail).", file=sys.stderr)
        return 1
    amap = load_map(app, region)
    if amap is not None:
        for src in sorted((app / "src").glob("*.[ch]*")):
            for m in CALL.finditer(src.read_text(encoding="utf-8")):
                if int(m.group(1), 16) not in amap:
                    print(f"region_config: {src.name}: AfroGameAddr({m.group(1)}) has no entry in "
                          f"app/regions/{region}.toml", file=sys.stderr)
                    return 1
    out = app / "region"
    out.mkdir(exist_ok=True)
    stamp = out / "region.txt"
    old = stamp.read_text(encoding="utf-8").strip() if stamp.is_file() else ""
    if old and old != region:
        for p in (app / "afro_switch_tables.toml", app / "assets" / "default.pe", app / "afro_icon.ico",
                  app / "generated" / "default" / "gen_v3.stamp"):
            p.unlink(missing_ok=True)
        print(f"region_config: disc changed from {old} to {region}; the game-derived files will be rebuilt")
    for name in ("afro_hooks.toml", "afro_functions.toml"):
        write_if_changed(out / name, move_toml((app / name).read_text(encoding="utf-8"), amap, name))
    write_if_changed(out / "afro_region.h", header(region, amap))
    write_if_changed(stamp, region + "\n")
    print(f"region_config: {NAMES[region]} disc")
    return 0


if __name__ == "__main__":
    sys.exit(main())
