#!/usr/bin/env python3
"""Encode the source snapshot that afrosetup.exe installs.

--out writes it as the release asset afrosetup-v<version>-files.bin. Since
0.3.10 the setup exe carries no source files: it uses that asset when it lies
next to the setup, or downloads it from this version's GitHub release, and
accepts it only when its SHA-256 equals the one in the --header file
(afrosetup_files.h), which the exe is compiled with. So the asset is packed
first, then the exe is built.
"""

from __future__ import annotations

import argparse
import hashlib
import pathlib
import struct


def ok_path(path: str) -> bool:
    if not path or path.startswith(("/", "\\")) or "\\" in path:
        return False
    for seg in path.split("/"):
        if seg in ("", ".", ".."):
            return False
        if any(not (c.isalnum() or c in "._-+") for c in seg):
            return False
    return True


# rexglue codegen writes these back with LF. A CRLF copy from a Windows checkout
# made every update differ from the installed file and run the codegen again.
LF_FILES = {"app/afrorecomp_manifest.toml"}


def collect(repo: pathlib.Path, overlay: pathlib.Path) -> list[tuple[str, bytes]]:
    skip_dirs = {".git"}
    skip_suffix = {".iso", ".xex", ".pe", ".exe", ".res", ".o", ".obj"}
    files: dict[str, pathlib.Path] = {}
    for root in (repo, overlay):
        for path in root.rglob("*"):
            if not path.is_file():
                continue
            rel = path.relative_to(root).as_posix()
            parts = set(path.relative_to(root).parts)
            if parts & skip_dirs:
                continue
            if path.suffix.lower() in skip_suffix and path.name != "install.bat":
                continue
            if path.name in ("afrosetup.exe", "afrosetup_payload.bin", "afrosetup_files.h") or (
                path.name.startswith("afrosetup-v") and path.name.lower().endswith((".exe", "-files.bin"))
            ):
                continue
            files[rel] = path
    out = []
    for rel in sorted(files):
        if not ok_path(rel):
            raise SystemExit(f"unsafe path: {rel}")
        data = files[rel].read_bytes()
        if rel in LF_FILES:
            data = data.replace(b"\r\n", b"\n")
        out.append((rel, data))
    return out


def encode(files: list[tuple[str, bytes]]) -> bytes:
    body = struct.pack("<I", len(files))
    for rel, data in files:
        raw = rel.encode("utf-8")
        body += struct.pack("<H", len(raw)) + raw + struct.pack("<Q", len(data)) + data
    return body


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=pathlib.Path, required=True, help="write afrosetup-v<version>-files.bin")
    parser.add_argument("--header", type=pathlib.Path, help="write afrosetup_files.h with the SHA-256 and size")
    parser.add_argument("--repo", type=pathlib.Path, required=True)
    parser.add_argument("--overlay", type=pathlib.Path, required=True)
    args = parser.parse_args()
    files = collect(args.repo, args.overlay)
    names = {rel for rel, _ in files}
    for need in ("app/VERSION", "tools/install.ps1", "tools/build_win.bat", "install.bat", "app/afro_hooks.toml"):
        if need not in names:
            raise SystemExit(f"snapshot missing {need}")
    version = dict(files)["app/VERSION"].decode("utf-8").strip()
    if version != "0.3.12":
        raise SystemExit(f"snapshot VERSION is {version!r}")
    ps1 = dict(files)["tools/install.ps1"].decode("utf-8")
    if "Refusing -Ref main" not in ps1 or "$LOCAL_TREE_VERSION = '0.3.12'" not in ps1:
        raise SystemExit("snapshot install.ps1 is not the local-tree build")
    if args.out.name != f"afrosetup-v{version}-files.bin":
        raise SystemExit(f"--out must be named afrosetup-v{version}-files.bin (the setup downloads that name)")
    body = encode(files)
    args.out.write_bytes(body)
    digest = hashlib.sha256(body).hexdigest()
    if args.header:
        args.header.write_text(
            "// Generated by pack_setup_payload.py. Not committed.\n"
            f"// {args.out.name}: the source files this setup accepts.\n"
            f'#define AFROSETUP_FILES_SHA256 "{digest}"\n'
            f"#define AFROSETUP_FILES_BYTES {len(body)}ULL\n",
            encoding="utf-8",
            newline="\n",
        )
    print(f"files: {len(files)}")
    print(f"bytes: {len(body)} ({args.out.name})")
    print(f"sha256: {digest}")


if __name__ == "__main__":
    main()
